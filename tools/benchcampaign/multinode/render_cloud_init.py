#!/usr/bin/env python3
"""Pin each machine's SSH host key before boot.

keys:   generate one ed25519 host key per host with ssh-keygen into
        HOST_KEY_DIR/<host>/ssh_host_ed25519_key{,.pub} (0700/0600).
render: write OUTPUT_DIR/<host>.user-data (cloud-config, 0600) installing that
        host key as the machine's only host key, disabling password login and
        background apt timers, plus OUTPUT_DIR/known_hosts keyed by
        HostKeyAlias=<host>, so the controller connects with
        ssh -o HostKeyAlias=<host> -o StrictHostKeyChecking=yes
           -o UserKnownHostsFile=OUTPUT_DIR/known_hosts root@<public-ip>
        and never trusts a key on first use.

The documents carry exactly one secret: the host's own private host key, which
belongs on that host. They never contain the controller's private key, an API
token or any other credential; --ssh-public-key is checked to be a public key.
Both directories must lie outside any Git work tree.
"""
import argparse
from pathlib import Path
import re
import subprocess
import sys

import mn_common as mc

PRIVATE_BEGIN = '-----BEGIN ' + 'OPENSSH PRIVATE KEY-----'
PRIVATE_END = '-----END ' + 'OPENSSH PRIVATE KEY-----'
PUBLIC_RE = re.compile(r'(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp(?:256|384|521)) [A-Za-z0-9+/=]+(?: [^\n]*)?')
HOST_PUBLIC_RE = re.compile(r'ssh-ed25519 [A-Za-z0-9+/=]+(?: [^\n]*)?')


def parse_args(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='command', required=True)
    k = sub.add_parser('keys')
    k.add_argument('--host-key-dir', required=True)
    k.add_argument('--host', action='append', required=True)
    k.add_argument('--ssh-keygen', default='ssh-keygen')
    r = sub.add_parser('render')
    r.add_argument('--host-key-dir', required=True)
    r.add_argument('--ssh-public-key', required=True, help='controller public key file (never the private key)')
    r.add_argument('--host', action='append', required=True)
    r.add_argument('--output-dir', required=True)
    return ap.parse_args(argv)


def check_host(host):
    return mc.check_name(host)


def generate_keys(host_key_dir, hosts, ssh_keygen='ssh-keygen', runner=mc.default_runner):
    mc.require_outside_repo(host_key_dir, 'host key dir')
    root = mc.private_dir(host_key_dir)
    for host in map(check_host, hosts):
        d = mc.private_dir(root / host)
        key = d / 'ssh_host_ed25519_key'
        if key.exists():
            raise mc.GuardError(f'{key} exists; host keys are generated once per campaign')
        rc, _, err = runner([ssh_keygen, '-q', '-t', 'ed25519', '-N', '', '-C', f'root@{host}', '-f', str(key)])
        if rc:
            raise mc.GuardError('ssh-keygen failed: ' + err.strip())
        key.chmod(0o600)
    return root


def read_public_key(path):
    text = Path(path).read_text()
    if 'PRIVATE KEY' in text:
        raise mc.GuardError(f'{path} is a private key; pass the .pub file')
    lines = [l for l in text.splitlines() if l.strip()]
    if len(lines) != 1 or not PUBLIC_RE.fullmatch(lines[0].strip()):
        raise mc.GuardError(f'{path} is not a single OpenSSH public key line')
    return lines[0].strip()


def read_host_key(host_key_dir, host):
    d = Path(host_key_dir) / host
    private = d / 'ssh_host_ed25519_key'
    public = d / 'ssh_host_ed25519_key.pub'
    if private.stat().st_mode & 0o077:
        raise mc.GuardError(f'{private} must be mode 0600')
    priv = private.read_text()
    lines = priv.strip().splitlines()
    if not lines or lines[0] != PRIVATE_BEGIN or lines[-1] != PRIVATE_END:
        raise mc.GuardError(f'{private} is not an OpenSSH private key')
    pub = public.read_text().strip()
    if not HOST_PUBLIC_RE.fullmatch(pub):
        raise mc.GuardError(f'{public} is not an ed25519 public key')
    return lines, pub


def cloud_config(host, private_lines, host_public, controller_public):
    body = '\n'.join('    ' + l for l in private_lines)
    return f"""#cloud-config
# Generated by render_cloud_init.py for {host}. Contains this host's own SSH host
# private key: keep the file private and outside any repository.
hostname: {host}
ssh_pwauth: false
disable_root: false
ssh_deletekeys: true
ssh_genkeytypes: []
ssh_keys:
  ed25519_private: |
{body}
  ed25519_public: {host_public}
ssh_authorized_keys:
  - {controller_public}
package_update: false
package_upgrade: false
runcmd:
  - [sh, -c, 'systemctl disable --now apt-daily.timer apt-daily-upgrade.timer || true']
  - [sh, -c, 'systemctl disable --now unattended-upgrades.service || true']
  - [sh, -c, 'install -d -m 0755 /srv/fdb-bench && date -u +%Y-%m-%dT%H:%M:%SZ > /srv/fdb-bench/cloud-init-done']
"""


def render(host_key_dir, ssh_public_key, hosts, output_dir):
    mc.require_outside_repo(host_key_dir, 'host key dir')
    mc.require_outside_repo(output_dir, 'cloud-init output dir')
    controller = read_public_key(ssh_public_key)
    out = mc.private_dir(output_dir)
    known = []
    written = []
    for host in map(check_host, hosts):
        lines, pub = read_host_key(host_key_dir, host)
        path = out / f'{host}.user-data'
        mc.write_private(path, cloud_config(host, lines, pub, controller))
        written.append(path)
        known.append(f'{host} {" ".join(pub.split()[:2])}')
    mc.write_private(out / 'known_hosts', '\n'.join(known) + '\n')
    return written


def main(argv=None):
    args = parse_args(argv)
    try:
        if args.command == 'keys':
            generate_keys(args.host_key_dir, args.host, args.ssh_keygen)
        else:
            for p in render(args.host_key_dir, args.ssh_public_key, args.host, args.output_dir):
                print(p)
    except (mc.GuardError, OSError) as exc:
        print('REFUSED: ' + str(exc), file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main())
