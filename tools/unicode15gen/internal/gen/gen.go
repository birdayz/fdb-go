// Package gen supplies offline, hash-verified input/output for the frozen norm generator.
package gen

import (
	"crypto/sha256"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"path/filepath"
	"strings"

	"mvdan.cc/gofumpt/format"
)

var (
	data   = flag.String("data", "", "directory containing verified Unicode 15 UCD inputs")
	output = flag.String("output", "", "normalization table output file")
)

func Init() {
	flag.Parse()
	if *data == "" || *output == "" {
		log.Fatal("-data and -output are required")
	}
	manifest, err := os.ReadFile(filepath.Join(*data, "SHA256SUMS"))
	if err != nil {
		log.Fatal(err)
	}
	for _, line := range strings.Split(strings.TrimSpace(string(manifest)), "\n") {
		fields := strings.Fields(line)
		if len(fields) != 2 {
			log.Fatal("malformed SHA256SUMS")
		}
		bytes, err := os.ReadFile(filepath.Join(*data, fields[1]))
		if err != nil {
			log.Fatal(err)
		}
		if fmt.Sprintf("%x", sha256.Sum256(bytes)) != fields[0] {
			log.Fatalf("SHA-256 mismatch: %s", fields[1])
		}
	}
}

func OpenUCDFile(name string) io.ReadCloser {
	f, err := os.Open(filepath.Join(*data, name))
	if err != nil {
		log.Fatal(err)
	}
	return f
}

func UnicodeVersion() string { return "15.0.0" }

func WriteVersionedGoFile(name, pkg string, body []byte) {
	// The upstream generator also emits an internal test-data table. The UCD
	// normalization corpus is our independent oracle, so that output is unused.
	if name == "data_test.go" {
		return
	}
	source := append([]byte("// Code generated by running \"go generate\" in golang.org/x/text. DO NOT EDIT.\n\npackage "+pkg+"\n\n"), body...)
	formatted, err := format.Source(source, format.Options{LangVersion: "go1.26", ModulePath: "fdb.dev"})
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*output, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
