#!/usr/bin/env python3
"""Generate immutable Unicode-15 classifiers and simple casing from verified UCD."""
import argparse
import hashlib
from pathlib import Path
import subprocess


def verify(root):
    for line in (root / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        digest, name = line.split(maxsplit=1)
        actual = hashlib.sha256((root / name).read_bytes()).hexdigest()
        if actual != digest:
            raise ValueError(f"{name}: SHA-256 mismatch: {actual}")


def ranges(points):
    result = []
    for cp in sorted(points):
        if result and result[-1][1] + 1 == cp:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result


def generate(root):
    verify(root)
    sets = {name: set() for name in (
        "L", "Nd", "Mn", "Mc", "Me", "Lu", "Ll", "Lt",
        "Other_Lowercase", "Other_Uppercase", "Ideographic", "White_Space")}
    lower, upper = {}, {}
    first = None
    for line in (root / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        cp, name, category = int(fields[0], 16), fields[1], fields[2]
        start = cp
        if name.endswith(", First>"):
            first = cp
            continue
        if name.endswith(", Last>"):
            if first is None:
                raise ValueError("range end without start")
            start, first = first, None
        for group in (category, "L" if category.startswith("L") else ""):
            if group in sets:
                sets[group].update(range(start, cp + 1))
        if fields[12]:
            upper[cp] = int(fields[12], 16)
        if fields[13]:
            lower[cp] = int(fields[13], 16)
    if first is not None:
        raise ValueError("unterminated UnicodeData range")
    for line in (root / "PropList.txt").read_text(encoding="utf-8").splitlines():
        body = line.split("#")[0].strip()
        if not body:
            continue
        span, name = (field.strip() for field in body.split(";"))
        if name not in sets:
            continue
        ends = [int(part, 16) for part in span.split("..")]
        sets[name].update(range(ends[0], ends[-1] + 1))
    cased = set()
    for line in (root / "DerivedCoreProperties.txt").read_text(encoding="utf-8").splitlines():
        fields = [field.strip() for field in line.split("#")[0].split(";")]
        if len(fields) < 2 or fields[1] != "Cased":
            continue
        ends = [int(part, 16) for part in fields[0].split("..")]
        cased.update(range(ends[0], ends[-1] + 1))
    derived = set().union(*(sets[name] for name in
                          ("Lu", "Ll", "Lt", "Other_Lowercase", "Other_Uppercase")))
    if cased != derived:
        raise ValueError("UnicodeData/PropList Cased union differs from DerivedCoreProperties")
    # C/S records define simple-fold equivalence classes. In particular, default
    # Unicode folding does not connect dotted/dotless I to ASCII I/i.
    groups = {}
    def group(cp):
        groups.setdefault(cp, {cp})
        return groups[cp]
    for line in (root / "CaseFolding.txt").read_text(encoding="utf-8").splitlines():
        fields = [s.strip() for s in line.split("#")[0].split(";")]
        if len(fields) < 3 or fields[1] not in ("C", "S"):
            continue
        cp, to = int(fields[0], 16), int(fields[2], 16)
        merged = group(cp) | group(to)
        for member in merged:
            groups[member] = merged
    fold = {}
    for cp, members in groups.items():
        ordered = sorted(members)
        fold[cp] = ordered[(ordered.index(cp) + 1) % len(ordered)]
    out = ["// Code generated by tools/unicode15gen/properties.py. DO NOT EDIT.",
           "", "package unicode15", "", 'const Version = "15.0.0"', ""]
    for name, points in sets.items():
        out.append(f"var {name} = &RangeTable{{")
        for field, subset in (("R16", [p for p in points if p <= 0xffff]),
                              ("R32", [p for p in points if p > 0xffff])):
            kind = "Range16" if field == "R16" else "Range32"
            out.append(f"\t{field}: []{kind}{{")
            for lo, hi in ranges(subset):
                out.append(f"\t\t{{0x{lo:x}, 0x{hi:x}, 1}},")
            out.append("\t},")
        out.extend(["}", ""])
    for name, mapping in (("lower", lower), ("upper", upper), ("fold", fold)):
        out.append(f"var {name} = map[rune]rune{{")
        for cp, to in sorted(mapping.items()):
            out.append(f"\t0x{cp:x}: 0x{to:x},")
        out.extend(["}", ""])
    return "\n".join(out).encode()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--formatter", required=True, help="repository-pinned gofumpt executable")
    args = parser.parse_args()
    formatted = subprocess.run([args.formatter, "-lang=go1.26", "-modpath=fdb.dev"], input=generate(args.data),
                               check=True, stdout=subprocess.PIPE).stdout
    args.output.write_bytes(formatted)
