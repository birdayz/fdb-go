"""Network-free isolated Git/CLI coverage with an explicitly injected tokenizer."""
import contextlib
import gzip
import hashlib
import importlib.metadata
import io
import json
from pathlib import Path
import runpy
import subprocess
import sys
import tempfile
import types
import unittest
from unittest import mock


SCRIPT = Path(__file__).with_name("fixture.py")
# Literal independent oracle: hash ordering, four-code/one-doc interleaving,
# and generated-file exclusion are deliberately not recomputed by this test.
ORDER = ["pkg/recordlayer/c.go", "pkg/recordlayer/e.go", "pkg/recordlayer/f.go",
         "docs/guide.md", "pkg/recordlayer/d.go", "pkg/recordlayer/b.go",
         "pkg/recordlayer/a.go", "docs/design.md"]


class ByteEncoding:
    name = "injected_test_bytes_not_cl100k"
    _mergeable_ranks = {bytes([i]): i for i in range(128)}

    def encode(self, text, disallowed_special=()):
        return list(text.encode())

    def decode_bytes(self, tokens):
        return bytes(tokens)


class GeneratorTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name) / "source"
        self.root.mkdir()
        self.data = {p: ("contents of " + p + "\n").encode() for p in ORDER}
        excluded = ["pkg/recordlayer/a_test.go", "pkg/recordlayer/nested/a.go",
                    "pkg/other/b.go", "docs/rfc-plan.md", "docs/review-plan.md",
                    "docs/prod-plan.md", "docs/panic-plan.md", "docs/test-plan.md",
                    "docs/nested/guide.md", "docs/guide.txt"]
        self.data.update({p: b"EXCLUDED\n" for p in excluded})
        self.data["pkg/recordlayer/generated.go"] = b"// Code generated by test. DO NOT EDIT.\n"
        for path, data in self.data.items():
            dest = self.root / path
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
        self.git("init", "-q")
        self.git("add", ".")
        self.git("-c", "user.name=Fixture Test", "-c", "user.email=fixture@example.invalid",
                 "commit", "-qm", "isolated inputs")
        self.revision = self.git("rev-parse", "HEAD").decode().strip()

    def git(self, *args):
        return subprocess.check_output(["git", "-C", str(self.root), *args])

    def invoke(self, budget, dest, encoding=None):
        encoding = encoding or ByteEncoding()
        module = types.ModuleType("tiktoken")
        module.get_encoding = lambda name: encoding if name == "cl100k_base" else None
        argv = [str(SCRIPT), "--revision", self.revision, "--source-root", str(self.root),
                "--output-dir", str(dest), "--tokens", str(budget)]
        # This runs the actual __main__/argparse/selection/truncation/emission path.
        with mock.patch.dict(sys.modules, {"tiktoken": module}), \
                mock.patch.object(sys, "argv", argv), \
                mock.patch.object(importlib.metadata, "version", return_value="injected-test-only"), \
                contextlib.redirect_stdout(io.StringIO()):
            runpy.run_path(str(SCRIPT), run_name="__main__")

    def test_cli_selection_partial_ranges_and_deterministic_output(self):
        blocks = [f'\n<source path="{p}">\n'.encode() + self.data[p] + b"\n</source>\n" for p in ORDER]
        last_header = f'\n<source path="{ORDER[-1]}">\n'.encode()
        expected_context = b"".join(blocks[:-1]) + last_header + self.data[ORDER[-1]][:5]
        budget = len(expected_context)
        dest = Path(self.tmp.name) / "output"
        self.invoke(budget, dest)
        manifest_bytes = (dest / "manifest.json").read_bytes()
        compressed = (dest / "messages_500k.json.gz").read_bytes()
        manifest = json.loads(manifest_bytes)
        raw = gzip.decompress(compressed)
        messages = json.loads(raw)
        self.assertEqual(messages, {"messages": [
            {"role": "system", "content": "Answer questions using the supplied source context."},
            {"role": "user", "content": expected_context.decode()}]})
        self.assertEqual(raw, (json.dumps(messages, ensure_ascii=False, separators=(",", ":")) + "\n").encode())
        self.assertEqual(manifest["source_revision"], self.revision)
        self.assertEqual(manifest["tokenizer_version"], "injected-test-only")
        self.assertEqual(manifest["encoding"], "injected_test_bytes_not_cl100k")
        self.assertEqual(manifest["context_tokens"], budget)
        self.assertEqual(manifest["context_bytes"], budget)
        self.assertEqual(manifest["context_sha256"], hashlib.sha256(expected_context).hexdigest())
        self.assertEqual(manifest["messages_json_bytes"], len(raw))
        self.assertEqual(manifest["messages_json_tokens"], len(raw))
        self.assertEqual(manifest["messages_json_sha256"], hashlib.sha256(raw).hexdigest())
        ranks = hashlib.sha256(b"".join((1).to_bytes(4, "big") + bytes([i]) + i.to_bytes(4, "big") for i in range(128))).hexdigest()
        self.assertEqual(manifest["mergeable_ranks_sha256"], ranks)
        self.assertEqual([s["path"] for s in manifest["sources"]], ORDER)
        offset = 0
        for i, source in enumerate(manifest["sources"]):
            path = ORDER[i]
            header_len = len(f'\n<source path="{path}">\n'.encode())
            self.assertEqual(source, {
                "path": path, "sha256": hashlib.sha256(self.data[path]).hexdigest(),
                "source_bytes": len(self.data[path]), "context_offset": offset,
                "header_bytes": header_len, "block_bytes": len(blocks[i]),
                "included_block_bytes": len(blocks[i]) if i < 7 else header_len + 5,
                "included_source_bytes": len(self.data[path]) if i < 7 else 5})
            offset += len(blocks[i])
        self.invoke(budget, dest)
        self.assertEqual((dest / "manifest.json").read_bytes(), manifest_bytes)
        self.assertEqual((dest / "messages_500k.json.gz").read_bytes(), compressed)
        self.assertEqual(compressed[4:8], b"\x00" * 4)  # gzip mtime

    def test_nonpositive_budget_does_not_emit(self):
        for budget in [0, -1]:
            with self.subTest(budget=budget):
                dest = Path(self.tmp.name) / f"invalid-{budget}"
                with contextlib.redirect_stderr(io.StringIO()), self.assertRaises(SystemExit) as result:
                    self.invoke(budget, dest)
                self.assertEqual(result.exception.code, 2)
                self.assertFalse(dest.exists())

    def test_utf8_complete_and_cut_boundary(self):
        path = ORDER[0]
        (self.root / path).write_text("éx", encoding="utf-8")
        self.git("add", path)
        self.git("-c", "user.name=Fixture Test", "-c", "user.email=fixture@example.invalid",
                 "commit", "-qm", "multibyte boundary")
        self.revision = self.git("rev-parse", "HEAD").decode().strip()
        header = f'\n<source path="{path}">\n'.encode()
        complete = Path(self.tmp.name) / "utf8-complete"
        self.invoke(len(header) + 2, complete)
        raw = gzip.decompress((complete / "messages_500k.json.gz").read_bytes())
        self.assertEqual(json.loads(raw)["messages"][1]["content"], header.decode() + "é")
        cut = Path(self.tmp.name) / "utf8-cut"
        with self.assertRaises(UnicodeDecodeError):
            self.invoke(len(header) + 1, cut)
        self.assertFalse(cut.exists())

    def test_insufficient_source_does_not_emit(self):
        dest = Path(self.tmp.name) / "insufficient"
        with self.assertRaisesRegex(ValueError, "insufficient distinct source"):
            self.invoke(1_000_000, dest)
        self.assertFalse(dest.exists())

    def test_nonroundtrip_boundary_does_not_emit(self):
        class NonRoundtrip(ByteEncoding):
            def decode_bytes(self, tokens):
                return bytes(tokens) + b"x"
        dest = Path(self.tmp.name) / "nonroundtrip"
        with self.assertRaisesRegex(ValueError, "truncated token boundary did not round trip"):
            self.invoke(100, dest, NonRoundtrip())
        self.assertFalse(dest.exists())


if __name__ == "__main__":
    unittest.main()
