package sqldriver_test

// The group-by output contract is an ORDINAL SLOT, not a name (RFC-197 item 5).
//
// This is the dimension the naming contract could not express: two grouping keys
// that share a leaf DISPLAY name. `GROUP BY t1.x, t2.x` emits two output columns
// both labelled X, and every post-aggregate reference to either one must reach
// the slot it was grouped under. A binder keyed on the rendered output name has
// exactly one entry for "X" and therefore one of the two keys — whichever the
// map saw last.
//
// Java is unambiguous that the currency here is positional:
// GroupByExpression.nestedResults builds the output row from Column.unnamedOf
// (GroupByExpression.java:754,758), the `_0`/`_1` labels are synthesized from
// position by Type.Record.normalizeFields and flagged throwaway by
// Field.isAutoGenerated (Type.java:2651,2922-2923), and the relational layer
// pulls its SELECT list up through that row by loop index
// (CompensateRecordConstructorRule.java:92), under the source comment "this must
// be aligned with _how_ the GroupByExpression composes its result set"
// (LogicalOperator.java:454).
//
// WHAT THIS DOES NOT COVER, stated up front because the obvious reading of it
// is wrong. These queries do NOT reach cascades_translator.go's
// groupByOutputBaker — the name-keyed plan-time binder that RFC-197 item 5
// exists to ordinalize. That is measured, not assumed: a panic at the head of
// bakeGroupByOutputRefs leaves every case here green and reds exactly one test
// in the whole aggregate suite (TestFDB_OrderByAggregateExpression, through
// translateSort). Disabling the binder's group-key arm outright
// (`keyOrds[key]` forced to miss) also leaves every case here green.
//
// So these are a NEGATIVE result, and that is their value: the collision
// dimension is already answered correctly, by a path that is not the binder.
// Anyone converting the binder must not read this file as the demonstration
// that the conversion worked — it would have passed before, during and after.
// What it does pin is that the ANSWER stays right, on the one shape the naming
// contract cannot express, in bare, computed and reversed-projection spellings.

import (
	"context"
	"database/sql"
	"fmt"
	"testing"
)

func TestFDB_AggregateGroupKeySlotCollision(t *testing.T) {
	t.Parallel()
	if clusterFilePath == "" {
		t.Skip("FDB not available (no Docker)")
	}
	ctx := context.Background()
	setup := openTestDB(t, "/testdb_aggslotcol")
	mwjoMustExec(t, setup, ctx, "CREATE DATABASE /testdb_aggslotcol")
	mwjoMustExec(t, setup, ctx, "CREATE SCHEMA TEMPLATE aggslotcol "+
		"CREATE TABLE t1 (id BIGINT NOT NULL, x BIGINT, PRIMARY KEY (id)) "+
		"CREATE TABLE t2 (id BIGINT NOT NULL, x BIGINT, PRIMARY KEY (id))")
	mwjoMustExec(t, setup, ctx, "CREATE SCHEMA /testdb_aggslotcol/s WITH TEMPLATE aggslotcol")
	dsn := fmt.Sprintf("fdbsql:///testdb_aggslotcol?cluster_file=%s&schema=s", clusterFilePath)
	db, err := sql.Open("fdbsql", dsn)
	if err != nil {
		t.Fatalf("sql.Open: %v", err)
	}
	t.Cleanup(func() { db.Close() })

	// The two X columns are drawn from DISJOINT ranges, so a slot mix-up cannot
	// be masked by coincidentally equal values: t1.x ∈ {1,2}, t2.x ∈ {10,20}.
	mwjoMustExec(t, db, ctx, "INSERT INTO t1 (id, x) VALUES (1, 1), (2, 2)")
	mwjoMustExec(t, db, ctx, "INSERT INTO t2 (id, x) VALUES (1, 10), (2, 20)")

	// The cross join yields one row per (t1.x, t2.x) pair, so every group has
	// COUNT 1 and the four (a,b) pairs are exactly the cross product.
	wantPairs := map[[2]int64]bool{{1, 10}: true, {1, 20}: true, {2, 10}: true, {2, 20}: true}

	for _, q := range []struct {
		name  string
		query string
	}{
		{"bare", "SELECT t1.x, t2.x, COUNT(*) FROM t1, t2 GROUP BY t1.x, t2.x"},
		{"computed", "SELECT t1.x + 0, t2.x + 0, COUNT(*) FROM t1, t2 GROUP BY t1.x, t2.x"},
		{
			"computed_reversed_select_order",
			"SELECT t2.x + 0, t1.x + 0, COUNT(*) FROM t1, t2 GROUP BY t1.x, t2.x",
		},
	} {
		t.Run(q.name, func(t *testing.T) {
			rows, err := db.QueryContext(ctx, q.query)
			if err != nil {
				t.Fatalf("%s: %v", q.query, err)
			}
			defer rows.Close()

			// The reversed-SELECT case reads (t2.x, t1.x); normalize to
			// (t1.x, t2.x) so one expectation set covers all three.
			swap := q.name == "computed_reversed_select_order"

			got := map[[2]int64]int64{}
			for rows.Next() {
				var a, b, n int64
				if err := rows.Scan(&a, &b, &n); err != nil {
					t.Fatalf("scan: %v", err)
				}
				if swap {
					a, b = b, a
				}
				got[[2]int64{a, b}] = n
			}
			if err := rows.Err(); err != nil {
				t.Fatalf("rows: %v", err)
			}

			if len(got) != len(wantPairs) {
				t.Fatalf("%s: got %d groups %v, want %d (%v)",
					q.query, len(got), got, len(wantPairs), wantPairs)
			}
			for pair, n := range got {
				if !wantPairs[pair] {
					t.Errorf("%s: group (t1.x=%d, t2.x=%d) is not a real pair — a "+
						"reference bound to the WRONG group-key slot; want one of %v",
						q.query, pair[0], pair[1], wantPairs)
				}
				if n != 1 {
					t.Errorf("%s: group (t1.x=%d, t2.x=%d) COUNT = %d, want 1",
						q.query, pair[0], pair[1], n)
				}
			}
		})
	}

	// The DISPLAY side of the same contract: both group-key output columns are
	// still labelled X. Ordinalizing the binding must not rename anything the
	// user sees — that is the whole point of separating the two (Java carries the
	// label as a separate Expression.name, empty for an unaliased aggregate,
	// Expression.java:72 / Expressions.java:251-253).
	t.Run("labels_still_collide", func(t *testing.T) {
		rows, err := db.QueryContext(ctx,
			"SELECT t1.x, t2.x, COUNT(*) FROM t1, t2 GROUP BY t1.x, t2.x")
		if err != nil {
			t.Fatalf("query: %v", err)
		}
		defer rows.Close()
		cols, err := rows.Columns()
		if err != nil {
			t.Fatalf("columns: %v", err)
		}
		if len(cols) != 3 || cols[0] != "X" || cols[1] != "X" {
			t.Errorf("result-set labels = %v, want the first two to both be X — "+
				"the display name stays the user's, only the BINDING became a slot",
				cols)
		}
	})
}

// The same contract, on the AGGREGATE half. `SUM(t1.x)` and `SUM(t2.x)` render
// to the same canonical output text, so a binder keyed on that text has one
// entry for two different aggregates.
func TestFDB_AggregateResultSlotCollision(t *testing.T) {
	t.Parallel()
	if clusterFilePath == "" {
		t.Skip("FDB not available (no Docker)")
	}
	ctx := context.Background()
	setup := openTestDB(t, "/testdb_aggrescol")
	mwjoMustExec(t, setup, ctx, "CREATE DATABASE /testdb_aggrescol")
	mwjoMustExec(t, setup, ctx, "CREATE SCHEMA TEMPLATE aggrescol "+
		"CREATE TABLE t1 (id BIGINT NOT NULL, x BIGINT, PRIMARY KEY (id)) "+
		"CREATE TABLE t2 (id BIGINT NOT NULL, x BIGINT, PRIMARY KEY (id))")
	mwjoMustExec(t, setup, ctx, "CREATE SCHEMA /testdb_aggrescol/s WITH TEMPLATE aggrescol")
	dsn := fmt.Sprintf("fdbsql:///testdb_aggrescol?cluster_file=%s&schema=s", clusterFilePath)
	db, err := sql.Open("fdbsql", dsn)
	if err != nil {
		t.Fatalf("sql.Open: %v", err)
	}
	t.Cleanup(func() { db.Close() })

	mwjoMustExec(t, db, ctx, "INSERT INTO t1 (id, x) VALUES (1, 1), (2, 2)")
	mwjoMustExec(t, db, ctx, "INSERT INTO t2 (id, x) VALUES (1, 10), (2, 20)")

	// Cross join, grouped by t1.id. Group 1: t1.x={1,1} sum 2, t2.x={10,20} sum 30.
	// Group 2: t1.x={2,2} sum 4, t2.x={10,20} sum 30.
	for _, q := range []struct {
		name  string
		query string
		want  map[int64][2]int64
	}{
		{
			"bare", "SELECT t1.id, SUM(t1.x), SUM(t2.x) FROM t1, t2 GROUP BY t1.id",
			map[int64][2]int64{1: {2, 30}, 2: {4, 30}},
		},
		{
			"computed", "SELECT t1.id, SUM(t1.x) + 0, SUM(t2.x) + 0 FROM t1, t2 GROUP BY t1.id",
			map[int64][2]int64{1: {2, 30}, 2: {4, 30}},
		},
	} {
		t.Run(q.name, func(t *testing.T) {
			rows, err := db.QueryContext(ctx, q.query)
			if err != nil {
				t.Fatalf("%s: %v", q.query, err)
			}
			defer rows.Close()
			got := map[int64][2]int64{}
			for rows.Next() {
				var id, s1, s2 int64
				if err := rows.Scan(&id, &s1, &s2); err != nil {
					t.Fatalf("scan: %v", err)
				}
				got[id] = [2]int64{s1, s2}
			}
			if err := rows.Err(); err != nil {
				t.Fatalf("rows: %v", err)
			}
			for id, want := range q.want {
				if got[id] != want {
					t.Errorf("%s: group id=%d gave (SUM(t1.x), SUM(t2.x)) = %v, want %v",
						q.query, id, got[id], want)
				}
			}
		})
	}
}
