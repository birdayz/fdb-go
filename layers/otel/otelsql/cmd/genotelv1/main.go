// genotelv1 writes compiled Go types for the OTEL_V1 schema template's
// records descriptor, which writers bind to the catalog's metadata with
// recordlayer.WithLocalFileDescriptor (otelsql.OpenTenantStore). The
// descriptor is the one the template's DDL compiles to, so regenerate after
// every template change with `just generate-otelv1`, which runs
//
//	bazelisk run //layers/otel/otelsql/cmd/genotelv1 -- "$PWD/layers/otel/otelsql/otelv1pb"
//
// and formats the output with gofumpt as `just fmt` does.
//
// otelv1pb's drift test fails while the generated descriptor and the DDL's
// differ.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"fdb.dev/layers/otel/otelsql"
	"fdb.dev/pkg/relational/core/embedded"
	gengo "google.golang.org/protobuf/cmd/protoc-gen-go/internal_gengo"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

// goPackage is the generated package's import path.
const goPackage = "fdb.dev/layers/otel/otelsql/otelv1pb;otelv1pb"

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genotelv1 <output directory>")
		os.Exit(2)
	}
	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "genotelv1:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	tmpl, err := embedded.BuildSchemaTemplateFromDDL(otelsql.TemplateDDL())
	if err != nil {
		return err
	}
	records := tmpl.Underlying().GetUnionDescriptor().ParentFile()
	fdp := protodesc.ToFileDescriptorProto(records)
	if fdp.Options == nil {
		fdp.Options = &descriptorpb.FileOptions{}
	}
	fdp.Options.GoPackage = proto.String(goPackage)
	// Every transitive import, dependencies first; the Record Layer's own
	// files are fdb.dev/gen's.
	var files []*descriptorpb.FileDescriptorProto
	seen := map[string]bool{}
	var walk func(protoreflect.FileDescriptor)
	walk = func(f protoreflect.FileDescriptor) {
		imports := f.Imports()
		for i := 0; i < imports.Len(); i++ {
			dep := imports.Get(i).FileDescriptor
			if seen[dep.Path()] {
				continue
			}
			seen[dep.Path()] = true
			walk(dep)
			p := protodesc.ToFileDescriptorProto(dep)
			if p.GetOptions().GetGoPackage() == "" {
				if p.Options == nil {
					p.Options = &descriptorpb.FileOptions{}
				}
				p.Options.GoPackage = proto.String("fdb.dev/gen;gen")
			}
			files = append(files, p)
		}
	}
	walk(records)
	files = append(files, fdp)
	req := &pluginpb.CodeGeneratorRequest{
		FileToGenerate: []string{fdp.GetName()},
		ProtoFile:      files,
		Parameter:      proto.String("paths=source_relative"),
	}
	plugin, err := protogen.Options{}.New(req)
	if err != nil {
		return err
	}
	var aliases []byte
	for _, f := range plugin.Files {
		if f.Generate {
			gengo.GenerateFile(plugin, f)
			aliases = arrayAliases(f)
		}
	}
	resp := plugin.Response()
	if resp.Error != nil {
		return fmt.Errorf("%s", resp.GetError())
	}
	if len(resp.File) != 1 {
		return fmt.Errorf("generated %d files, want 1", len(resp.File))
	}
	for name, content := range map[string][]byte{"otel_v1.pb.go": []byte(resp.File[0].GetContent()), "otel_v1_arrays.go": aliases} {
		path := filepath.Join(out, name)
		if err := os.WriteFile(path, content, 0o644); err != nil {
			return err
		}
		fmt.Println("wrote", path)
	}
	return nil
}

// arrayAliases names the template's ARRAY wrapper messages ({ repeated
// values = 1; }, generated as XType_<uuid>, one per declaring table or
// struct) after the column that holds them: SPANS_STR_ATTRS.
func arrayAliases(f *protogen.File) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by genotelv1. DO NOT EDIT.\n\npackage otelv1pb\n\n")
	b.WriteString("// The template's ARRAY wrapper messages, named <MESSAGE>_<COLUMN>.\n")
	names := map[string]string{}
	for _, m := range f.Messages {
		for _, field := range m.Fields {
			w := field.Message
			if w == nil || !strings.HasPrefix(string(w.Desc.Name()), "__type__") || len(w.Fields) != 1 || !w.Fields[0].Desc.IsList() {
				continue
			}
			names[m.GoIdent.GoName+"_"+string(field.Desc.Name())] = w.GoIdent.GoName
		}
	}
	keys := make([]string, 0, len(names))
	for k := range names {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b.WriteString("type (\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%s = %s\n", k, names[k])
	}
	b.WriteString(")\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err) // the generator's own syntax
	}
	return formatted
}
